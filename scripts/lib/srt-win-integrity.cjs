const { createHash } = require("node:crypto");
const { lstatSync, readFileSync } = require("node:fs");
const { join } = require("node:path");
const pins = require("../../src/permissions/srt-win-pins.json");

const RECEIPTS_DIRECTORY = join(__dirname, "../../src/permissions/generated");
const TARGETS = Object.freeze({ x64: "x86_64-pc-windows-msvc", arm64: "aarch64-pc-windows-msvc" });
function digest(bytes) { return createHash("sha256").update(bytes).digest("hex"); }
function readPlainFile(path) {
  try {
    if (!lstatSync(path).isFile()) throw new Error("srt-win-integrity-mismatch");
    return readFileSync(path);
  } catch (cause) { throw new Error("srt-win-integrity-mismatch", { cause }); }
}
function assertBuildReceipt(receipt, arch) {
  if (!Object.hasOwn(TARGETS, arch) || !receipt || receipt.schemaVersion !== 1 ||
      receipt.sourceRevision !== pins.source.revision || receipt.sourceArchiveSha256 !== pins.source.sha256 ||
      receipt.nativePatchSha256 !== pins.nativePatchSha256 || receipt.rustToolchain !== pins.rustToolchain ||
      receipt.target !== TARGETS[arch] || !/^[a-f0-9]{64}$/.test(receipt.binarySha256)) {
    throw new Error(`srt-win-integrity-mismatch: ${arch}`);
  }
}
function assertSrtWinReceiptModule() {
  const json = readPlainFile(join(RECEIPTS_DIRECTORY, "srt-win-build-receipts.json"));
  const serialized = JSON.stringify(JSON.parse(json), null, 2);
  const expected = `// Generated by build-srt-win.mjs.\nexport default ${serialized};\n`;
  if (readPlainFile(join(RECEIPTS_DIRECTORY, "srt-win-build-receipts.js")).toString() !== expected) {
    throw new Error("srt-win-receipt-module-mismatch");
  }
  return digest(json);
}
function readBuildReceipts() {
  return JSON.parse(readPlainFile(join(RECEIPTS_DIRECTORY, "srt-win-build-receipts.json")));
}
function assertSrtWinVendor(vendorDirectory, arches = Object.keys(TARGETS), receipts = readBuildReceipts()) {
  for (const arch of arches) {
    const expected = Object.hasOwn(receipts, arch) ? receipts[arch] : undefined;
    assertBuildReceipt(expected, arch);
    const directory = join(vendorDirectory, "srt-win", arch);
    const receipt = JSON.parse(readPlainFile(join(directory, "build-receipt.json")));
    assertBuildReceipt(receipt, arch);
    for (const key of Object.keys(expected)) {
      if (receipt[key] !== expected[key]) throw new Error(`srt-win-integrity-mismatch: ${arch}`);
    }
    if (digest(readPlainFile(join(directory, "srt-win.exe"))) !== expected.binarySha256) {
      throw new Error(`srt-win-integrity-mismatch: ${arch}`);
    }
  }
}
function assertUpstreamSrtWinVendor(vendorDirectory, arches = Object.keys(pins.sha256)) {
  for (const arch of arches) {
    if (!Object.hasOwn(pins.sha256, arch) || digest(readPlainFile(join(vendorDirectory, "srt-win", arch, "srt-win.exe"))) !== pins.sha256[arch]) {
      throw new Error(`srt-win-upstream-integrity-mismatch: ${arch}`);
    }
  }
}
function assertSrtWinBuildInputs(vendorDirectory) {
  if (digest(readPlainFile(join(vendorDirectory, "srt-win", "persistent-denies.patch"))) !== pins.nativePatchSha256) {
    throw new Error("srt-win-native-patch-integrity-mismatch");
  }
}
module.exports = { TARGETS, RECEIPTS_DIRECTORY, digest, readPlainFile, assertBuildReceipt, readBuildReceipts,
  assertSrtWinVendor, assertUpstreamSrtWinVendor, assertSrtWinBuildInputs, assertSrtWinReceiptModule };
