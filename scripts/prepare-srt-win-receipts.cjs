const { existsSync, mkdirSync, writeFileSync } = require("node:fs");
const { join } = require("node:path");
const { RECEIPTS_DIRECTORY } = require("./lib/srt-win-integrity.cjs");

// An empty map lets non-native builds compile and always refuses helper execution.
function prepareSrtWinReceipts() {
  mkdirSync(RECEIPTS_DIRECTORY, { recursive: true });
  for (const [name, contents] of [
    ["srt-win-build-receipts.json", "{}\n"],
    ["srt-win-build-receipts.js", "// Generated by build-srt-win.mjs.\nexport default {};\n"],
  ]) {
    const path = join(RECEIPTS_DIRECTORY, name);
    if (!existsSync(path)) writeFileSync(path, contents, { flag: "wx" });
  }
}
module.exports = { prepareSrtWinReceipts };
if (require.main === module) prepareSrtWinReceipts();
