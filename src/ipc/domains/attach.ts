// Convert the shared array into a Set once at module load for O(1) lookup
// in the file-picker hot path. Source of truth lives in the shared module.
const DENY_EXTENSIONS = new Set<string>(DENY_LIST);

/**
 * Session-scoped allowlist of paths the user has explicitly authorized
 * (via the OS file picker or clipboard paste). `readImage` and
 * `openExternal` MUST consult this set before touching the filesystem
 * — otherwise a compromised renderer could pass an arbitrary path
 * (`/Users/.../secrets.json` symlinked to `*.png`) and exfiltrate
 * its contents via the returned dataURL, or launch an attacker-planted
 * binary via shell.openPath.
 *
 * Module-scope, app-lifetime — there is no security benefit to clearing
 * across navigations, and re-prompting the user every chat would be
 * hostile UX. The threat model only requires that paths are
 * user-acknowledged at LEAST ONCE in this app run.
 *
 * Bounded by {@link ATTACH_ALLOWLIST_MAX} with insertion-order LRU
 * eviction (Set iteration order = insertion order; oldest evicted first).
 * Prevents unbounded memory growth in long-lived sessions where a power
 * user might attach thousands of files. Eviction risk is benign — if the
 * user re-attaches a previously evicted path, the OS picker re-authorizes
 * it. The cap is high enough (10k) that normal usage never trips it.
 */
const ATTACH_ALLOWLIST_MAX = 10_000;
const ATTACH_PATH_ALLOWLIST = new Set<string>();
// Only paths generated by this process enter this set. A late renderer refusal
// may revoke their capabilities, but never pathname-delete them: Node exposes
// no cross-platform compare-and-unlink primitive, so a replacement race would
// otherwise risk unlinking a user-managed file.
const CLIPBOARD_TEMP_IMAGE_PATHS = new Set<string>();

function authorizePath(p: string): void {
  // Re-add to move existing entries to the tail (Set iteration is
  // insertion-order, so deleting + re-adding refreshes recency).
  if (ATTACH_PATH_ALLOWLIST.has(p)) ATTACH_PATH_ALLOWLIST.delete(p);
  ATTACH_PATH_ALLOWLIST.add(p);
  while (ATTACH_PATH_ALLOWLIST.size > ATTACH_ALLOWLIST_MAX) {
    const oldest = ATTACH_PATH_ALLOWLIST.values().next().value;
    if (oldest === undefined) break;
    ATTACH_PATH_ALLOWLIST.delete(oldest);
    CLIPBOARD_TEMP_IMAGE_PATHS.delete(oldest);
  }
}

function authorizeClipboardTempImage(
  filePath: string,
): void {
  authorizePath(filePath);
  CLIPBOARD_TEMP_IMAGE_PATHS.add(filePath);
}

/** A minted drop token is redeemable for this window, then refused. */
export const DROP_TOKEN_TTL_MS = 60_000;
/** Bounds the pending-token map; oldest entries are evicted first. */
const DROP_TOKEN_MAX_PENDING = 32;

/** Why a dropped item was not bound to the token. Stable codes, never prose. */
type DropRejectReason =
  | "denied-extension"
  | "sensitive-path"
  | "not-a-file"
  | "not-found"
  | "too-many";

/** A dropped file main validated and bound to a token (metadata only, no bytes). */
type DroppedFile = OpenFileResult["files"][number];

/**
 * Main-held pending composer drops, keyed by a one-time token.
 *
 * Why a token at all, when the preload hands main the paths: the paths reach
 * main only through `aveDrop.prepareFileDrop(files)`, which resolves real
 * OS-backed `File`s via `webUtils.getPathForFile` in the preload and invokes
 * `registerDrop` in the same call. Nothing in the main world can send a path
 * string to this channel. Registering authorizes nothing; it validates and
 * binds. The renderer must then REDEEM the token for the files to enter
 * {@link ATTACH_PATH_ALLOWLIST}, so a drop that lands outside the composer (and
 * is never redeemed) widens nothing and simply expires.
 *
 * The binding is to the exact validated file list, the webContents that
 * registered it, and an expiry. Redemption consumes the entry on first lookup,
 * whatever the outcome, mirroring `workspace.pickRoot({ ackToken })`.
 */
const pendingDrops = new Map<string, { senderId: number; files: DroppedFile[]; expires: number }>();

function prunePendingDrops(now: number): void {
  for (const [token, pending] of pendingDrops) {
    if (now > pending.expires) pendingDrops.delete(token);
  }
  while (pendingDrops.size >= DROP_TOKEN_MAX_PENDING) {
    const oldest = pendingDrops.keys().next().value;
    if (oldest === undefined) break;
    pendingDrops.delete(oldest);
  }
}

function senderIdOf(e: IpcMainInvokeEvent): number | null {
  const id = (e.sender as { id?: unknown } | undefined)?.id;
  return typeof id === "number" ? id : null;
}

function sensitiveForRead(p: string): boolean {
  return isSensitivePath(caseFoldForMatch(canonicalizePathForMatch(p)), "read") !== null;
}

/**
 * The allowlist holds the spelling that was authorized, not what it points to
 * now: a symlink that passed the checks can be retargeted afterwards. Every use
 * resolves it again and re-applies the same refusals to the current target.
 */
async function resolveAuthorizedTarget(
  filePath: string,
): Promise<{ ok: true; real: string } | { ok: false; error: string }> {
  let real: string;
  try {
    real = await fs.realpath(filePath);
  } catch {
    return { ok: false, error: "not-found" };
  }
  if (sensitiveForRead(real)) return { ok: false, error: "sensitive-path" };
  if (DENY_EXTENSIONS.has(getExt(real))) return { ok: false, error: "denied_extension" };
  return { ok: true, real };
}

/** Validate one dropped path into metadata, or say why it is refused. */
async function validateDroppedPath(
  p: string,
): Promise<{ ok: true; file: DroppedFile } | { ok: false; reason: DropRejectReason }> {
  const ext = getExt(p);
  if (DENY_EXTENSIONS.has(ext)) return { ok: false, reason: "denied-extension" };
  // Both the dropped spelling and its real target: a harmless-looking name may
  // be a symlink to a credential file.
  if (sensitiveForRead(p)) return { ok: false, reason: "sensitive-path" };
  let real: string;
  try {
    real = await fs.realpath(p);
  } catch {
    return { ok: false, reason: "not-found" };
  }
  if (sensitiveForRead(real)) return { ok: false, reason: "sensitive-path" };
  if (DENY_EXTENSIONS.has(getExt(real))) return { ok: false, reason: "denied-extension" };
  try {
    const stat = await fs.stat(real);
    if (!stat.isFile()) return { ok: false, reason: "not-a-file" };
    const imageFormat = await sniffImageFilePrefix(real);
    return {
      ok: true,
      file: {
        path: p,
        name: path.basename(p),
        ext,
        bytes: stat.size,
        isImage: imageFormat !== null && imageFormat !== undefined,
        mimeType: imageFormat?.mimeType,
      },
    };
  } catch {
    return { ok: false, reason: "not-found" };
  }
}

/**
 * Preserve the old permissive pre-decode DoS guard. The decoded image cap
 * itself comes from the shared composer image input contract.
 */
const MAX_CLIPBOARD_BASE64_INPUT_CHARS = MAX_COMPOSER_IMAGE_BYTES * 2;

/** The file name's extension; a dot in a directory name (`~/.config/notes`) is not one. */
function getExt(p: string): string {
  const name = path.basename(p);
  const i = name.lastIndexOf(".");
  return i >= 0 ? name.slice(i + 1).toLowerCase() : "";
}

/**
 * Reads only the bytes needed by the shared magic sniffer. Picker metadata
 * must reflect file content, but generic files must never be buffered merely
 * to decide whether they are images.
 */
async function sniffImageFilePrefix(filePath: string) {
  const handle = await fs.open(filePath, "r");
  try {
    const prefix = Buffer.alloc(12);
    const { bytesRead } = await handle.read(prefix, 0, prefix.length, 0);
    return sniffComposerImageFormat(prefix.subarray(0, bytesRead));
  } finally {
    await handle.close();
  }
}


export interface OpenFileResult {
  canceled: boolean;
  files: Array<{
    path: string;
    name: string;
    ext: string;
    bytes: number;
    isImage: boolean;
    mimeType?: string;
  }>;
  rejected: string[]; // paths rejected by deny-list
}

/** Step 1 of a composer drop: main validated the dropped paths and bound a token. */
export type RegisterDropResult =
  | { ok: true; token: string; rejected: Array<{ name: string; reason: DropRejectReason }> }
  | { ok: false; error: "unauthorized" | "invalid-payload" | "nothing-attachable"; rejected?: Array<{ name: string; reason: DropRejectReason }> };

/** Step 2: the token was redeemed and exactly its files were authorized. */
export type RedeemDropResult =
  | { ok: true; files: OpenFileResult["files"] }
  | { ok: false; error: "unauthorized" | "drop-token-invalid" | "drop-token-expired" };

export interface ReadImageResult {
  ok: boolean;
  dataUrl?: string;
  mimeType?: string;
  width?: number;
  height?: number;
  bytes?: number;
  error?: string;
}

export interface SaveClipboardImageInput {
  /**
   * Base64-encoded image bytes (no `data:` prefix). Format is autodetected
   * from the leading magic bytes — PNG / JPEG / GIF / WebP / BMP all
   * supported. Renderer does not need to negotiate the format up front.
   */
  base64: string;
}

export interface SaveClipboardImageResult {
  ok: boolean;
  path?: string;
  width?: number;
  height?: number;
  bytes?: number;
  mimeType?: string;
  dataUrl?: string;
  error?: string;
}

/** Result of revoking an unadopted app-owned clipboard image capability. */
export interface DiscardClipboardImageResult {
  ok: boolean;
  /** Kept on disk for OS temp cleanup rather than risking pathname-delete races. */
  retained?: true;
  error?: "unauthorized" | "clipboard-image-not-owned";
}

export function registerAttachHandlers(deps: IpcDeps): void {
  const { auditLogger, getMainWindow } = deps;

  ipcMain.handle(CHANNELS.attach.openFile, async (e): Promise<OpenFileResult> => {
    if (!validateHostRendererSender(e)) {
      auditUnauthorized(auditLogger, CHANNELS.attach.openFile, e);
      return { canceled: true, files: [], rejected: [] };
    }
    const win = getMainWindow();
    if (!win) return { canceled: true, files: [], rejected: [] };

    const result = await dialog.showOpenDialog(win, {
      title: t("mainDialog.attachTitle"),
      properties: ["openFile", "multiSelections"],
    });
    if (result.canceled || result.filePaths.length === 0) {
      return { canceled: true, files: [], rejected: [] };
    }

    const files: OpenFileResult["files"] = [];
    const rejected: string[] = [];
    for (const p of result.filePaths) {
      const ext = getExt(p);
      if (DENY_EXTENSIONS.has(ext)) {
        rejected.push(p);
        continue;
      }
      try {
        const stat = await fs.stat(p);
        const imageFormat = await sniffImageFilePrefix(p);
        const isImage = imageFormat !== null && imageFormat !== undefined;
        files.push({
          path: p,
          name: path.basename(p),
          ext,
          bytes: stat.size,
          isImage,
          mimeType: imageFormat?.mimeType,
        });
        // Authorize this exact path for downstream readImage / openExternal.
        // The user just acknowledged it via the OS picker, so subsequent
        // reads are no longer blind-trusting renderer-supplied paths.
        authorizePath(p);
      } catch {
        rejected.push(p);
      }
    }
    return { canceled: false, files, rejected };
  });

  ipcMain.handle(
    CHANNELS.attach.registerDrop,
    async (e, rawPaths: unknown): Promise<RegisterDropResult> => {
      if (!validateHostRendererSender(e)) {
        auditUnauthorized(auditLogger, CHANNELS.attach.registerDrop, e);
        return { ok: false, error: "unauthorized" };
      }
      const senderId = senderIdOf(e);
      if (senderId === null) return { ok: false, error: "unauthorized" };
      if (
        !Array.isArray(rawPaths)
        || rawPaths.length === 0
        || !rawPaths.every((p): p is string => typeof p === "string" && p.length > 0 && path.isAbsolute(p))
      ) {
        return { ok: false, error: "invalid-payload" };
      }
      const files: DroppedFile[] = [];
      const rejected: Array<{ name: string; reason: DropRejectReason }> = [];
      for (const p of rawPaths) {
        if (files.length >= MAX_COMPOSER_ATTACHMENT_COUNT) {
          rejected.push({ name: path.basename(p), reason: "too-many" });
          continue;
        }
        const verdict = await validateDroppedPath(p);
        if (verdict.ok) files.push(verdict.file);
        else rejected.push({ name: path.basename(p), reason: verdict.reason });
      }
      if (files.length === 0) return { ok: false, error: "nothing-attachable", rejected };
      const now = Date.now();
      prunePendingDrops(now);
      const token = randomBytes(32).toString("base64url");
      pendingDrops.set(token, { senderId, files, expires: now + DROP_TOKEN_TTL_MS });
      return { ok: true, token, rejected };
    },
  );

  ipcMain.handle(
    CHANNELS.attach.redeemDrop,
    async (e, rawToken: unknown): Promise<RedeemDropResult> => {
      if (!validateHostRendererSender(e)) {
        auditUnauthorized(auditLogger, CHANNELS.attach.redeemDrop, e);
        return { ok: false, error: "unauthorized" };
      }
      if (typeof rawToken !== "string" || rawToken.length === 0) {
        return { ok: false, error: "drop-token-invalid" };
      }
      const pending = pendingDrops.get(rawToken);
      // Consume on first lookup regardless of what follows: a token is never
      // worth a second attempt, from this sender or any other.
      if (pending) pendingDrops.delete(rawToken);
      if (!pending || pending.senderId !== senderIdOf(e)) {
        return { ok: false, error: "drop-token-invalid" };
      }
      if (Date.now() > pending.expires) return { ok: false, error: "drop-token-expired" };
      for (const file of pending.files) authorizePath(file.path);
      return { ok: true, files: pending.files };
    },
  );

  ipcMain.handle(
    CHANNELS.attach.readImage,
    async (e, filePath: string): Promise<ReadImageResult> => {
      if (!validateHostRendererSender(e)) {
        auditUnauthorized(auditLogger, CHANNELS.attach.readImage, e);
        return { ok: false, error: "unauthorized" };
      }
      try {
        // Path-allowlist gate: the renderer can ask to read any string,
        // so we MUST verify the path was previously authorized via the
        // OS file picker. Without this gate, a compromised renderer
        // (XSS in a plugin webview, malicious paste-bridge, etc.) could
        // exfiltrate arbitrary files by symlinking them to a `.png`
        // and calling readImage(arbitrary_path).
        if (!ATTACH_PATH_ALLOWLIST.has(filePath)) {
          return { ok: false, error: "path_not_authorized" };
        }
        const target = await resolveAuthorizedTarget(filePath);
        if (!target.ok) return { ok: false, error: target.error };
        // Stat first so we can refuse to buffer a multi-GB file. Vision
        // APIs reject anything beyond ~20MB, so 25MB cap is generous.
        const stat = await fs.stat(target.real);
        if (stat.size > MAX_COMPOSER_IMAGE_BYTES) {
          return {
            ok: false,
            error: `image_too_large: ${stat.size} > ${MAX_COMPOSER_IMAGE_BYTES}`,
          };
        }
        if (!await sniffImageFilePrefix(target.real)) {
          return { ok: false, error: "not_image" };
        }
        const buf = await fs.readFile(target.real);
        if (buf.length > MAX_COMPOSER_IMAGE_BYTES) {
          return {
            ok: false,
            error: `image_too_large: ${buf.length} > ${MAX_COMPOSER_IMAGE_BYTES}`,
          };
        }
        // Re-sniff after the full read so a file replacement race cannot make
        // a claimed image MIME disagree with the bytes sent to a provider.
        const imageFormat = sniffComposerImageFormat(buf);
        if (!imageFormat) {
          return { ok: false, error: "not_image" };
        }
        const mimeType = imageFormat.mimeType;
        const img = nativeImage.createFromBuffer(buf);
        const { width, height } = img.getSize();
        const dataUrl = `data:${mimeType};base64,${buf.toString("base64")}`;
        return {
          ok: true,
          dataUrl,
          mimeType,
          width,
          height,
          bytes: buf.length,
        };
      } catch (err) {
        return {
          ok: false,
          error: errorMessage(err),
        };
      }
    },
  );

  ipcMain.handle(
    CHANNELS.attach.saveClipboardImage,
    async (e, input: SaveClipboardImageInput): Promise<SaveClipboardImageResult> => {
      if (!validateHostRendererSender(e)) {
        auditUnauthorized(auditLogger, CHANNELS.attach.saveClipboardImage, e);
        return { ok: false, error: "unauthorized" };
      }
      try {
        // Cap base64 size before decoding. Without this, a compromised
        // renderer can flood `os.tmpdir()` with multi-GB writes and/or
        // trigger native image-decoder vulnerabilities (e.g. WebP libwebp
        // CVE class) on attacker-shaped buffers in the main process.
        if (typeof input?.base64 !== "string") {
          return { ok: false, error: "invalid_payload" };
        }
        if (input.base64.length > MAX_CLIPBOARD_BASE64_INPUT_CHARS) {
          // base64 is ~4/3 the binary size, *2 is a generous bound that
          // still rejects pathological multi-GB strings before Buffer.from.
          return {
            ok: false,
            error: `clipboard_too_large: ${input.base64.length} > ${MAX_CLIPBOARD_BASE64_INPUT_CHARS}`,
          };
        }
        const buf = Buffer.from(input.base64, "base64");
        if (buf.length > MAX_COMPOSER_IMAGE_BYTES) {
          return {
            ok: false,
            error: `clipboard_too_large: ${buf.length} > ${MAX_COMPOSER_IMAGE_BYTES}`,
          };
        }
        // Clipboard content has no trusted extension. The same strict magic
        // contract used by subscription input keeps a false image MIME from
        // reaching a provider or the app-owned temp directory.
        const detected = sniffComposerImageFormat(buf);
        if (!detected) {
          return { ok: false, error: "not_image" };
        }
        // Buffer accepts whitespace and other permissive base64 spellings.
        // Return one canonical spelling that downstream validators accept.
        const canonicalBase64 = buf.toString("base64");
        const img = nativeImage.createFromBuffer(buf);
        const { width, height } = img.getSize();
        // A fresh private directory is the secure boundary. A random basename
        // in the shared OS temp directory still lets an attacker race the path
        // before creation; mkdtemp reserves the directory atomically.
        const targetDir = await fs.mkdtemp(path.join(os.tmpdir(), "ave-clip-"));
        const target = path.join(targetDir, "image." + detected.extension);
        // wx binds the capability to the exact file this process created.
        await fs.writeFile(target, buf, { flag: "wx", mode: 0o600 });
        // Authorize for downstream readImage / openExternal — we just
        // wrote this file ourselves so it's safe to read back.
        authorizeClipboardTempImage(target);
        const dataUrl = `data:${detected.mimeType};base64,${canonicalBase64}`;
        return {
          ok: true,
          path: target,
          width,
          height,
          bytes: buf.length,
          mimeType: detected.mimeType,
          dataUrl,
        };
      } catch (err) {
        return {
          ok: false,
          error: errorMessage(err),
        };
      }
    },
  );

  ipcMain.handle(
    CHANNELS.attach.discardClipboardImage,
    async (e, filePath: unknown): Promise<DiscardClipboardImageResult> => {
      if (!validateHostRendererSender(e)) {
        auditUnauthorized(auditLogger, CHANNELS.attach.discardClipboardImage, e);
        return { ok: false, error: "unauthorized" };
      }
      if (typeof filePath !== "string") {
        return { ok: false, error: "clipboard-image-not-owned" };
      }
      if (!CLIPBOARD_TEMP_IMAGE_PATHS.has(filePath)) {
        return { ok: false, error: "clipboard-image-not-owned" };
      }

      // Do not lstat+unlink here. A pathname may be replaced after an identity
      // check and before unlink; Node has no cross-platform compare-and-unlink
      // operation. Revocation is safe, while the app-created temp file can be
      // collected by the operating system without touching user files.
      ATTACH_PATH_ALLOWLIST.delete(filePath);
      CLIPBOARD_TEMP_IMAGE_PATHS.delete(filePath);
      return { ok: true, retained: true };
    },
  );
  ipcMain.handle(
    CHANNELS.attach.openExternal,
    async (e, filePath: string): Promise<{ ok: boolean; error?: string }> => {
      if (!validateHostRendererSender(e)) {
        auditUnauthorized(auditLogger, CHANNELS.attach.openExternal, e);
        return { ok: false, error: "unauthorized" };
      }
      try {
        // Same allowlist gate as readImage. Without it, a compromised
        // renderer could trigger `shell.openPath("/path/to/malicious.app")`
        // and execute attacker-planted binaries. Re-applying the
        // deny-list also blocks dangerous extensions even if the path
        // somehow ends up in the allowlist via a future bug.
        if (!ATTACH_PATH_ALLOWLIST.has(filePath)) {
          return { ok: false, error: "path_not_authorized" };
        }
        if (DENY_EXTENSIONS.has(getExt(filePath))) {
          return { ok: false, error: "denied_extension" };
        }
        const target = await resolveAuthorizedTarget(filePath);
        if (!target.ok) return { ok: false, error: target.error };
        const result = await shell.openPath(target.real);
        if (result) return { ok: false, error: result };
        return { ok: true };
      } catch (err) {
        return {
          ok: false,
          error: errorMessage(err),
        };
      }
    },
  );
}
