/**
 * Composer attachment domain IPC handlers.
 * Covers: ave:attach:openFile, ave:attach:readImage,
 *         ave:attach:saveClipboardImage, ave:attach:discardClipboardImage,
 *         ave:attach:openExternal
 *
 * Renderer reaches these via window.ave.attach.* (see preload.ts).
 */
